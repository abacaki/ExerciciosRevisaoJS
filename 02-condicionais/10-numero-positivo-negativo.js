// Considere:
//
// let numero = -5;
//
// Mostre:
// "Positivo" se for maior que zero.
// "Negativo" se for menor que zero.
// "Zero" se for igual a zero.

// Escreva sua solução abaixo:

let numero = -5;

if (numero > 0) {
    console.log("Número positivo");
}
else if (numero < 0) {
    console.log("Número negativo");
} else {
    console.log("Número zero");
}